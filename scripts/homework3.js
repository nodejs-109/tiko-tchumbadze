// რომ მოცემული წელი ნაკიანია და თუ არა 
// მაგ შემთხვევაში უნდა გამოიტანოთ რომ წელი არ არის ნაკიანი.
function leapYear(year) {
    if ((year % 4 === 0 && year % 100 !== 0) || (year % 400 === 0)) {
        return "მოცემული წელი ნაკიანია";
    } else {
        return "მოცემული წელი არ არის ნაკიანი";
    }
}
