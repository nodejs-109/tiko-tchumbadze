function calculator() {
    let num1 = prompt("შეიყვანეთ რიცხვი 1:");
    if (isNaN(num1) === true) {
        console.log("რიცხვი არასწორ ფორმატშია შეყვანილი!")
    } else {
        let action = prompt("შეიყვანეთ მოქმედება:");
        let num2 = prompt("შეიყვანეთ რიცხვი 2:");
        if (isNaN(num2) === true) {
            console.log("რიცხვი არასწორ ფორმატშია შეყვანილი!")
        } else {
            num1 = Number(num1);
            num2 = Number(num2);
        
            if (action === "+") {
                console.log(num1 + num2);
            } else if (action === "-") {
                console.log(num1 - num2);
            } else if (action === "*") {
                console.log(num1 * num2);
            } else if (action === "/") {
                console.log(num1 / num2);
            } else {
                console.log("არასწორი ოპერატორია შეყვანილი, გთხოვთ, აქედან შეიყვანოთ ერთ-ერთი! +,-,*,/")
            }
            
        }

    }
}
